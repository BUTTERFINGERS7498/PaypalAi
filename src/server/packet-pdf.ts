// Feature B3: the dispute evidence packet as a one-page PDF. PayPal's provide-evidence accepts documents only as
// JPG, GIF, PNG or PDF, so the packet is rendered as plain text in a PDF (no dependency: a minimal PDF 1.4 writer).
// The same file is offered for download in the console, so anyone can see exactly what PayPal would receive.
import type { Dispute, EvidenceRecord, Purchase } from './types.ts';

/** PDF text strings: escape \ ( ) and drop characters outside printable ASCII (Helvetica WinAnsi is enough here). */
function pdfText(s: string): string {
  return s
    .replace(/[→]/g, '->').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[–—]/g, '-').replace(/…/g, '...')
    .replace(/[^\x20-\x7E]/g, '?')
    .replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

/** Greedy word wrap to a fixed character width (Helvetica 9pt fits about 100 characters on A4). */
function wrap(line: string, width: number): string[] {
  const out: string[] = [];
  let cur = '';
  for (const word of line.split(/\s+/)) {
    if (!word) continue;
    if ((cur + ' ' + word).trim().length > width) {
      if (cur) out.push(cur);
      cur = word.length > width ? word.slice(0, width) : word;
    } else {
      cur = (cur + ' ' + word).trim();
    }
  }
  if (cur) out.push(cur);
  return out.length ? out : [''];
}

/** Builds a single-page PDF with the given lines (title first, bigger). Lines past the page are cut with a note. */
export function textPdf(title: string, lines: string[]): Buffer {
  const width = 100;
  const body = lines.flatMap((l) => (l === '' ? [''] : wrap(l, width)));
  const maxLines = 70;
  const shown = body.length > maxLines ? [...body.slice(0, maxLines - 1), '(cut: the full packet is in the JSON download)'] : body;
  const ops = [
    'BT', '/F1 14 Tf', '50 800 Td', `(${pdfText(title)}) Tj`, '/F1 9 Tf', '0 -22 Td', '11 TL',
    ...shown.map((l) => `(${pdfText(l)}) '`),
    'ET',
  ].join('\n');
  const objects = [
    '<< /Type /Catalog /Pages 2 0 R >>',
    '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
    '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
    '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>',
    `<< /Length ${Buffer.byteLength(ops, 'latin1')} >>\nstream\n${ops}\nendstream`,
  ];
  let pdf = '%PDF-1.4\n';
  const offsets: number[] = [];
  objects.forEach((o, i) => {
    offsets.push(Buffer.byteLength(pdf, 'latin1'));
    pdf += `${i + 1} 0 obj\n${o}\nendobj\n`;
  });
  const xref = Buffer.byteLength(pdf, 'latin1');
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  pdf += offsets.map((o) => `${String(o).padStart(10, '0')} 00000 n \n`).join('');
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xref}\n%%EOF\n`;
  return Buffer.from(pdf, 'latin1');
}

/** The dispute packet as PDF lines: verdict, purchase, mandate signature, chain status and every record's hash. */
export function packetPdf(d: Dispute, p: Purchase | null, records: EvidenceRecord[], chain: { valid: boolean; head_hash: string }): Buffer {
  const pk = d.packet;
  const lines: string[] = [];
  lines.push(`Dispute ${d.paypal_dispute_id ?? d.id}${d.simulated ? ' (SIMULATED: created locally, not from PayPal)' : ''}`);
  lines.push(`Reason: ${d.reason} | Amount disputed: ${d.amount.currency_code} ${d.amount.value}`);
  if (p) lines.push(`Purchase ${p.id}: ${p.item_name}, ${p.amount.currency_code} ${p.amount.value}, PayPal order ${p.paypal_order_id ?? 'n/a'}, capture ${p.paypal_capture_id ?? 'n/a'}`);
  lines.push('');
  if (pk) {
    lines.push(`VERDICT (computed by code from the evidence): ${pk.verdict} -> action: ${pk.action}`);
    lines.push(`Summary: ${pk.summary}`);
    lines.push('');
    lines.push('Narrative:');
    lines.push(pk.narrative);
    lines.push('');
  }
  const m = records.find((r) => r.mandate)?.mandate;
  if (m) {
    lines.push(`Mandate ${m.id} v${m.version} (${m.status}): cap ${m.limits.monthly_cap}, categories ${m.limits.categories.join(', ')}, approval above ${m.limits.approval_above}`);
    lines.push(`Mandate signature (ed25519, Sentry demo key): ${m.signature}`);
    lines.push('');
  }
  lines.push(`Evidence chain: ${chain.valid ? 'VALID' : 'INVALID'} | head hash ${chain.head_hash}`);
  lines.push('Records (oldest first): seq, decision, within mandate, record id, hash');
  for (const r of records) lines.push(`#${r.seq} ${r.decision} ${r.within_mandate ? 'within' : 'OUTSIDE'} ${r.record_id} ${r.hash}`);
  lines.push('');
  lines.push('Each record hash covers the previous one (hash = sha256(prev_hash + canonical JSON)); changing any record breaks every later hash.');
  lines.push('Generated by Sentry. PayPal sandbox only; signatures use the Sentry demo key, not an AP2/FIDO credential.');
  return textPdf('Sentry dispute evidence packet', lines);
}
